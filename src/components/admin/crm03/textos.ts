type L = "he" | "en" | "ru" | "ar";
const lang = (): L => (["he", "en", "ru", "ar"].includes(localeConfig.lang) ? localeConfig.lang : "en") as L;

/** Plural por las reglas del idioma: he one/two/other, en one/other, ru one/few/many, ar zero/one/two/few/many/other. */
export function plural(n: number, formas: Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }): string {
  const c = new Intl.PluralRules(lang()).select(n);
  return (formas[c] ?? formas.other).replace("{n}", n.toLocaleString(localeConfig.lang === "ar" ? "ar" : "en-US"));
}

